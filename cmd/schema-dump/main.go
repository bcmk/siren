// This program applies all migrations to a temporary database,
// then prints the resulting schema or, with --schema-snapshot, one script that builds it
package main

import (
	"context"
	"fmt"
	"regexp"
	"strings"

	"github.com/spf13/pflag"
	"github.com/testcontainers/testcontainers-go/modules/postgres"

	"github.com/bcmk/siren/v6/internal/db"
	"github.com/bcmk/siren/v6/internal/pgtest"
	"github.com/bcmk/siren/v6/lib/cmdlib"
)

var (
	checkErr = cmdlib.CheckErr
	linf     = cmdlib.Linf
)

var (
	// Created by create_hypertable, which needs the table without it
	insertBlockerRegexp  = regexp.MustCompile(`(?m)^CREATE TRIGGER ts_insert_blocker .*\n`)
	sessionSettingRegexp = regexp.MustCompile(`(?m)^(SET |SELECT pg_catalog\.set_config\().*\n`)
	dumpCommentRegexp    = regexp.MustCompile(`(?m)^--.*\n`)
	blankLinesRegexp     = regexp.MustCompile(`\n{3,}`)
)

func main() {
	schemaSnapshot := pflag.Bool("schema-snapshot", false, "print the schema snapshot an empty database starts from")
	pflag.Parse()
	ctx := context.Background()

	linf("starting PostgreSQL container...")
	pgContainer, err := pgtest.Run(ctx, "test")
	checkErr(err)
	defer func() { checkErr(pgContainer.Terminate(ctx)) }()

	connStr, err := pgContainer.ConnectionString(ctx, "sslmode=disable")
	checkErr(err)

	linf("applying migrations...")
	database := db.NewDatabase(connStr, false, 0)
	defer func() { checkErr(database.Close()) }()

	database.ApplyMigrationsOneByOne()

	if *schemaSnapshot {
		linf("dumping the schema snapshot...")
		printSchemaSnapshot(ctx, pgContainer, database)
		return
	}

	linf("dumping schema...\n")
	printSchema(database)
}

// printSchemaSnapshot prints a script that builds what the migrations built,
// which MustExecScript runs as one implicit transaction.
// It names no owner, so the role running it owns everything,
// and changes no session setting, as the connection stays in use.
func printSchemaSnapshot(ctx context.Context, pgContainer *postgres.PostgresContainer, database db.Database) {
	// So refreshing the schema snapshot changes nothing without a new migration
	database.MustExec(`update schema_migrations set applied_at = 0`)
	schema, err := pgtest.PgDump(
		ctx,
		pgContainer,
		"test",
		"--schema-only",
		"--no-owner",
		"--no-comments")
	checkErr(err)
	rows, err := pgtest.PgDump(ctx, pgContainer, "test", "--data-only", "--inserts", "--schema=public")
	checkErr(err)
	script := insertBlockerRegexp.ReplaceAllString(schema, "") + rows
	script = sessionSettingRegexp.ReplaceAllString(script, "")
	script = blankLinesRegexp.ReplaceAllString(dumpCommentRegexp.ReplaceAllString(script, ""), "\n\n")
	script = strings.TrimLeft(script, "\n")

	fmt.Println("-- Generated by cmd/schema-dump --schema-snapshot.")
	fmt.Println("-- TestSchemaSnapshotMatchesMigrations holds it to the migrations.")
	fmt.Print(script)
	var name, column string
	var interval int64
	database.MustQuery(`
		select hypertable_name, column_name, integer_interval
		from timescaledb_information.dimensions
		order by hypertable_name`,
		nil,
		db.ScanTo{&name, &column, &interval},
		func() {
			fmt.Printf(
				"select public.create_hypertable('public.%s', public.by_range('%s', %d), create_default_indexes => false);\n",
				name,
				column,
				interval)
		})
}

type column struct {
	name         string
	dataType     string
	collation    *string
	isNullable   string
	defaultValue *string
}

type index struct {
	name string
	def  string
}

type check struct {
	name string
	def  string
}

type table struct {
	columns    []column
	dimensions []string
	indexes    []index
	checks     []check
	reloptions []string
}

func printSchema(database db.Database) {
	tables := make(map[string]*table)
	var tableOrder []string

	var tableName, columnName, dataType, isNullable string
	var collation, columnDefault *string
	database.MustQuery(`
		select
			c.table_name,
			c.column_name,
			c.data_type,
			c.collation_name,
			c.is_nullable,
			c.column_default
		from information_schema.columns c
		join information_schema.tables t
			on c.table_name = t.table_name
			and c.table_schema = t.table_schema
		where c.table_schema = 'public'
			and t.table_type = 'BASE TABLE'
		order by c.table_name, c.ordinal_position`,
		nil,
		db.ScanTo{&tableName, &columnName, &dataType, &collation, &isNullable, &columnDefault},
		func() {
			if tables[tableName] == nil {
				tables[tableName] = &table{}
				tableOrder = append(tableOrder, tableName)
			}
			tables[tableName].columns = append(tables[tableName].columns, column{
				name:         columnName,
				dataType:     dataType,
				collation:    collation,
				isNullable:   isNullable,
				defaultValue: columnDefault,
			})
		})

	var dimTable, dimDef string
	database.MustQuery(`
		select
			hypertable_name,
			case dimension_type
				when 'Time' then format(
					'hypertable by %s, chunk interval %s',
					column_name,
					coalesce(integer_interval::text, time_interval::text))
				else format('hash partitioned by %s, %s partitions', column_name, num_partitions)
			end
		from timescaledb_information.dimensions
		where hypertable_schema = 'public'
		order by hypertable_name, dimension_number`,
		nil,
		db.ScanTo{&dimTable, &dimDef},
		func() {
			if tables[dimTable] != nil {
				tables[dimTable].dimensions = append(tables[dimTable].dimensions, dimDef)
			}
		})

	var indexName, indexTable, indexDef string
	database.MustQuery(`
		select indexname, tablename, indexdef
		from pg_indexes
		where schemaname = 'public'
		order by tablename, indexname`,
		nil,
		db.ScanTo{&indexName, &indexTable, &indexDef},
		func() {
			if tables[indexTable] != nil {
				tables[indexTable].indexes = append(tables[indexTable].indexes, index{
					name: indexName,
					def:  indexDef,
				})
			}
		})

	var checkName, checkTable, checkDef string
	database.MustQuery(`
		select conname, relname, pg_get_constraintdef(c.oid)
		from pg_constraint c
		join pg_class r on c.conrelid = r.oid
		join pg_namespace n on r.relnamespace = n.oid
		where n.nspname = 'public' and c.contype = 'c'
		order by relname, conname`,
		nil,
		db.ScanTo{&checkName, &checkTable, &checkDef},
		func() {
			if tables[checkTable] != nil {
				tables[checkTable].checks = append(tables[checkTable].checks, check{
					name: checkName,
					def:  checkDef,
				})
			}
		})

	var optTable, opt string
	database.MustQuery(`
		select relname, unnest(reloptions)
		from pg_class c
		join pg_namespace n on c.relnamespace = n.oid
		where n.nspname = 'public'
			and c.relkind = 'r'
			and c.reloptions is not null
		order by relname`,
		nil,
		db.ScanTo{&optTable, &opt},
		func() {
			if tables[optTable] != nil {
				tables[optTable].reloptions = append(tables[optTable].reloptions, opt)
			}
		})

	for i, name := range tableOrder {
		if i > 0 {
			fmt.Println()
		}
		t := tables[name]
		fmt.Printf("table %s\n", name)

		maxName, maxType := 0, 0
		for _, col := range t.columns {
			if len(col.name) > maxName {
				maxName = len(col.name)
			}
			typeStr := col.dataType
			if col.collation != nil && *col.collation != "default" {
				typeStr += fmt.Sprintf(" collate %q", *col.collation)
			}
			if len(typeStr) > maxType {
				maxType = len(typeStr)
			}
		}

		for _, col := range t.columns {
			typeStr := col.dataType
			if col.collation != nil && *col.collation != "default" {
				typeStr += fmt.Sprintf(" collate %q", *col.collation)
			}
			nullable := ""
			if col.isNullable == "NO" {
				nullable = "not null"
			}
			def := ""
			if col.defaultValue != nil {
				def = fmt.Sprintf("default %s", *col.defaultValue)
			}
			fmt.Printf("    %-*s  %-*s  %-8s  %s\n",
				maxName, col.name,
				maxType, typeStr,
				nullable,
				def)
		}

		if len(t.dimensions) > 0 {
			fmt.Println()
			for _, dim := range t.dimensions {
				fmt.Printf("    %s\n", dim)
			}
		}

		if len(t.indexes) > 0 {
			fmt.Println()
			for _, idx := range t.indexes {
				fmt.Printf("    index %s: %s\n", idx.name, idx.def)
			}
		}

		if len(t.checks) > 0 {
			fmt.Println()
			for _, chk := range t.checks {
				fmt.Printf("    check %s: %s\n", chk.name, chk.def)
			}
		}

		if len(t.reloptions) > 0 {
			fmt.Println()
			for _, opt := range t.reloptions {
				fmt.Printf("    option %s\n", opt)
			}
		}
	}
}
